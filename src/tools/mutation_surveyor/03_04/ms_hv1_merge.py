#!/usr/bin/env python3
"""
ms_hv1_merge.py

Process HV1 traces from the MS trace-processed output generated by ms_trace_process.py.

Input:
    *_MS_trace_processed.xlsx

Output:
    Excel file with sheets:
      - Traces: HV1 trace-level records with adjusted HV1 columns
      - LID: one merged HV1 profile per LID
      - Summary: counts for pair status, review class, and flags

Main logic:
1. Keep HV1F / HV1R only.
2. Trim each trace to HV1 target region: 16024-16365.
3. Select one primary HV1F and one primary HV1R per LID.
4. Merge selected HV1F + HV1R into one HV1 profile per LID.
5. Preserve trace-boundary ranges; do not merge adjacent ranges such as
   16024-16189 + 16190-16365 into 16024-16365.
6. Detect strict mismatch between selected HV1F/HV1R inside overlap.
7. Flag same-position multi-calls within each selected adjusted trace.
8. Scan selected source traces before adjusted trimming for het calls.
9. Split HV1 flags into:
   - HV1 Flag list: full/informational flag list
   - HV1 Review-triggering Flag list: flags that trigger Review
10. Do not require truthset columns and do not calculate truthset concordance.
"""

import argparse
import re
from collections import Counter
from pathlib import Path

import pandas as pd

HV1_TARGET = [(16024.0, 16365.0)]
HV1_POLYC = [(16180.0, 16195.0)]

IUPAC = {
    "W": set("AT"),
    "R": set("AG"),
    "M": set("AC"),
    "K": set("GT"),
    "Y": set("CT"),
    "S": set("CG"),
    "D": set("AGT"),
    "H": set("ACT"),
    "V": set("ACG"),
    "B": set("CGT"),
    "N": set("ACGT"),
}

PHP_CODES = set("RMSKYWVHBDN")


def parse_args():
    p = argparse.ArgumentParser(description="Merge HV1F/HV1R traces by LID from *_MS_trace_processed.xlsx")
    p.add_argument("--input", required=True, help="Input *_MS_trace_processed.xlsx from ms_trace_process.py")
    p.add_argument("--output", required=True, help="Output xlsx with HV1 merged profiles")
    return p.parse_args()


def safe_str(x):
    return "" if pd.isna(x) else str(x).strip()


def normalize_text(x):
    return " ".join(safe_str(x).split())


def format_num(x):
    return str(int(float(x))) if float(x).is_integer() else str(x)


def parse_range_pair(text):
    m = re.match(r"^(\d+(?:\.\d+)?)\s*-\s*(\d+(?:\.\d+)?)$", safe_str(text))
    if not m:
        return None
    a = float(m.group(1))
    b = float(m.group(2))
    return (min(a, b), max(a, b))


def parse_multi_ranges(text):
    out = []
    for a, b in re.findall(r"(\d+(?:\.\d+)?)\s*-\s*(\d+(?:\.\d+)?)", safe_str(text)):
        a = float(a)
        b = float(b)
        out.append((min(a, b), max(a, b)))
    return out


def intersect_ranges(r, allowed):
    if r is None:
        return []
    out = []
    for lo, hi in allowed:
        a = max(r[0], lo)
        b = min(r[1], hi)
        if a <= b:
            out.append((a, b))
    return out


def overlap_pair(r1, r2):
    if r1 is None or r2 is None:
        return None
    lo = max(r1[0], r2[0])
    hi = min(r1[1], r2[1])
    return (lo, hi) if lo <= hi else None


def normalize_ranges(ranges, merge_adjacent=False):
    if not ranges:
        return []
    ranges = sorted(ranges)
    merged = [ranges[0]]
    for a, b in ranges[1:]:
        pa, pb = merged[-1]
        cond = a <= pb if not merge_adjacent else a <= pb + 1
        if cond:
            merged[-1] = (pa, max(pb, b))
        else:
            merged.append((a, b))
    return merged


def format_ranges(ranges):
    return " ".join(f"{format_num(a)}-{format_num(b)}" for a, b in ranges)


def in_any_range(pos, ranges):
    return any(lo <= pos <= hi for lo, hi in ranges)


def parse_variant_tokens(text):
    out = []
    if pd.isna(text) or str(text).strip() == "":
        return out
    for tok in re.split(r"[,\s]+", str(text).strip()):
        if not tok:
            continue
        m = re.match(r"^(\d+(?:\.\d+)?)([A-Za-z_]+)$", tok)
        if not m:
            continue
        pos = float(m.group(1))
        allele = m.group(2).replace("_HET", "_het")
        out.append((pos, allele, f"{format_num(pos)}{allele}"))
    return out


def token_sort_key(tok):
    m = re.match(r"^(\d+(?:\.\d+)?)([A-Za-z_]+)$", safe_str(tok))
    if not m:
        return (10**9, tok)
    return (float(m.group(1)), m.group(2))


def merge_unique_tokens(texts, allowed_ranges):
    seen = {}
    for txt in texts:
        for pos, allele, tok in parse_variant_tokens(txt):
            if in_any_range(pos, allowed_ranges):
                key = (pos, allele.upper())
                if key not in seen:
                    seen[key] = tok
    return " ".join(sorted(seen.values(), key=token_sort_key))


def alleles_compatible(a1, a2):
    a1 = safe_str(a1).replace("_HET", "_het")
    a2 = safe_str(a2).replace("_HET", "_het")
    c1 = a1.replace("_het", "")
    c2 = a2.replace("_het", "")
    if c1 == c2:
        return True
    s1 = IUPAC.get(c1)
    s2 = IUPAC.get(c2)
    if s1 is not None and s2 is None and c2 in s1:
        return True
    if s2 is not None and s1 is None and c1 in s2:
        return True
    if s1 is not None and s2 is not None and len(s1.intersection(s2)) > 0:
        return True
    return False


def normalize_allele_for_trace_compare(allele):
    """Normalize allele text for strict HV1F/HV1R trace comparison.

    This is intentionally stricter than IUPAC compatibility:
    C vs Y, A vs R, and A vs N are mismatches.
    Only identical normalized allele strings are considered matching.
    """
    return safe_str(allele).replace("_HET", "_het").upper()


def variant_dict_in_ranges(text, ranges):
    return {pos: allele for pos, allele, _ in parse_variant_tokens(text) if in_any_range(pos, ranges)}


def variant_allele_sets_in_ranges(text, ranges):
    """Return position -> set(normalized allele strings) for variants inside ranges.

    Unlike variant_dict_in_ranges(), this preserves same-position multi-calls
    so mismatch detection cannot accidentally overwrite an earlier allele.
    """
    out = {}
    for pos, allele, _ in parse_variant_tokens(text):
        if in_any_range(pos, ranges):
            out.setdefault(pos, set()).add(normalize_allele_for_trace_compare(allele))
    return out


def same_position_multicall_positions(*rows):
    """Find positions where one selected adjusted trace has >1 distinct allele call.

    This checks each selected trace independently. It is not used to compare
    HV1F against HV1R; F/R disagreement is handled by HV1 trace mismatch.
    """
    positions = set()
    for row in rows:
        if row is None:
            continue
        per_pos = {}
        for pos, allele, _ in parse_variant_tokens(row.get("HV1 Trace Variants Adjusted", "")):
            per_pos.setdefault(pos, set()).add(normalize_allele_for_trace_compare(allele))
        for pos, alleles in per_pos.items():
            if len(alleles) > 1:
                positions.add(pos)
    return sorted(positions)


def trim_trace_hv1(ms_range_text, variant_text):
    rr = parse_range_pair(ms_range_text)
    trimmed_ranges = intersect_ranges(rr, HV1_TARGET)
    kept = {}
    for pos, allele, tok in parse_variant_tokens(variant_text):
        if in_any_range(pos, trimmed_ranges):
            key = (pos, allele.upper())
            if key not in kept:
                kept[key] = tok
    return format_ranges(trimmed_ranges), " ".join(sorted(kept.values(), key=token_sort_key))


def trace_coverage_length(row):
    ranges = parse_multi_ranges(row.get("HV1 Trace Range Adjusted", ""))
    return sum(max(0.0, b - a + 1) for a, b in ranges)


def trace_has_php(row):
    for _, allele, _ in parse_variant_tokens(row.get("HV1 Trace Variants Adjusted", "")):
        if allele.upper() in PHP_CODES:
            return True
    return False


def trace_has_het(row):
    return "het" in safe_str(row.get("HV1 Trace Variants Adjusted", "")).lower()


def trace_polyc_variant_count(row):
    return sum(
        1
        for pos, _, _ in parse_variant_tokens(row.get("HV1 Trace Variants Adjusted", ""))
        if in_any_range(pos, HV1_POLYC)
    )


def trace_indel_outside_polyc_count(row):
    count = 0
    for pos, allele, _ in parse_variant_tokens(row.get("HV1 Trace Variants Adjusted", "")):
        is_insertion = not float(pos).is_integer()
        is_deletion = "DEL" in allele.upper()
        if (is_insertion or is_deletion) and not in_any_range(pos, HV1_POLYC):
            count += 1
    return count


def trace_num(row):
    v = safe_str(row.get("Trace #", ""))
    try:
        return int(float(v))
    except Exception:
        return 10**9


def score_trace(row):
    coverage = trace_coverage_length(row)
    ranges = parse_multi_ranges(row.get("HV1 Trace Range Adjusted", ""))
    full_bonus = 1000 if covers_segment(ranges, HV1_TARGET[0]) else 0
    penalty = 0
    penalty += 20 * trace_polyc_variant_count(row)
    penalty += 50 if trace_has_php(row) else 0
    penalty += 50 if trace_has_het(row) else 0
    penalty += 80 * trace_indel_outside_polyc_count(row)
    return coverage + full_bonus - penalty


def select_best_trace(sub_df):
    if sub_df.empty:
        return None
    sub = sub_df.copy()
    sub["_hv1_score"] = sub.apply(score_trace, axis=1)
    sub["_trace_num"] = sub.apply(trace_num, axis=1)
    sub = sub.sort_values(["_hv1_score", "_trace_num", "Sample Name"], ascending=[False, True, True])
    return sub.iloc[0].to_dict()


def select_trace_pair(group_df):
    out = {}
    counts = {}
    for primer in ["HV1F", "HV1R"]:
        sub = group_df[group_df["Primer"].astype(str).str.upper() == primer].copy()
        counts[primer] = len(sub)
        out[primer] = select_best_trace(sub)
    return out, counts


def mismatch_positions_between_two_rows(row1, row2):
    if row1 is None or row2 is None:
        return []
    r1 = parse_multi_ranges(row1.get("HV1 Trace Range Adjusted", ""))
    r2 = parse_multi_ranges(row2.get("HV1 Trace Range Adjusted", ""))
    overlap_ranges = []
    for a in r1:
        for b in r2:
            ov = overlap_pair(a, b)
            if ov is not None:
                overlap_ranges.append(ov)
    overlap_ranges = normalize_ranges(overlap_ranges, merge_adjacent=False)
    if not overlap_ranges:
        return []
    d1 = variant_allele_sets_in_ranges(row1.get("HV1 Trace Variants Adjusted", ""), overlap_ranges)
    d2 = variant_allele_sets_in_ranges(row2.get("HV1 Trace Variants Adjusted", ""), overlap_ranges)
    positions = sorted(set(d1.keys()).union(d2.keys()))
    mismatches = []
    for pos in positions:
        alleles1 = d1.get(pos)
        alleles2 = d2.get(pos)
        if alleles1 is None or alleles2 is None or alleles1 != alleles2:
            mismatches.append(format_num(pos))
    return mismatches


def covers_segment(ranges, target):
    lo, hi = target
    return any(a <= lo and b >= hi for a, b in ranges)


def source_het_flags(*rows):
    flags = set()
    for row in rows:
        if row is None:
            continue
        source_text = row.get("Variant Converted 2", "")
        if "het" not in safe_str(source_text).lower():
            continue
        flags.add("HV1 source het")
        for pos, allele, _ in parse_variant_tokens(source_text):
            if "het" in allele.lower() and in_any_range(pos, HV1_POLYC):
                flags.add("HV1 source polyC het")
    return sorted(flags)


def build_hv1_flags(pair_status, merged_ranges, merged_variants, mismatch_text, hv1f_row=None, hv1r_row=None):
    """
    Return two semicolon-separated flag lists:
    - full_flags: informational + review-triggering flags
    - review_flags: only flags that should send the LID to Review

    HV1 polyC SNP-only variants are informational only.
    HV1 polyC insertion/deletion/PHP and source het are review-triggering.
    """
    full_flags = []
    review_flags = []
    tokens = parse_variant_tokens(merged_variants)

    def add(flag, review=True):
        full_flags.append(flag)
        if review:
            review_flags.append(flag)

    if pair_status != "OK":
        add(pair_status, review=True)

    if not covers_segment(merged_ranges, HV1_TARGET[0]):
        add("No full HV1 region", review=True)

    if mismatch_text:
        add("HV1 trace mismatch", review=True)

    polyc_tokens = [(pos, allele, tok) for pos, allele, tok in tokens if in_any_range(pos, HV1_POLYC)]

    if polyc_tokens:
        add("HV1 polyC variant", review=False)

    if any(not float(pos).is_integer() for pos, _, _ in polyc_tokens):
        add("HV1 polyC insertion", review=True)

    if any("DEL" in allele.upper() for _, allele, _ in polyc_tokens):
        add("HV1 polyC deletion", review=True)

    if any(allele.upper() in PHP_CODES for _, allele, _ in polyc_tokens):
        add("HV1 polyC PHP", review=True)

    if any(allele.upper() in PHP_CODES for _, allele, _ in tokens):
        add("PHP", review=True)

    if "het" in safe_str(merged_variants).lower():
        add("het", review=True)

    for pos, allele, _ in tokens:
        is_insertion = not float(pos).is_integer()
        is_deletion = "DEL" in allele.upper()
        if (is_insertion or is_deletion) and not in_any_range(pos, HV1_POLYC):
            add("HV1 indel outside polyC", review=True)
            break

    for flag in source_het_flags(hv1f_row, hv1r_row):
        add(flag, review=True)

    multicall_positions = same_position_multicall_positions(hv1f_row, hv1r_row)
    if multicall_positions:
        pos_text = ",".join(format_num(pos) for pos in multicall_positions)
        add(f"HV1 same-position multi-call: {pos_text}", review=True)

    full_out = "; ".join(sorted(set(full_flags)))
    review_out = "; ".join(sorted(set(review_flags)))
    return full_out, review_out


def review_class(review_triggering_flag_list):
    return "Auto - no flag" if safe_str(review_triggering_flag_list) == "" else "Review"


def first_value(row_or_series, col, default=""):
    try:
        return row_or_series.get(col, default)
    except Exception:
        return default


def main():
    args = parse_args()
    df = pd.read_excel(args.input)
    df.columns = [str(c).strip() for c in df.columns]

    required = ["LID", "Primer", "MS Range", "Variant Converted 2"]
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns: {missing}")

    df = df[df["Primer"].astype(str).str.upper().isin(["HV1F", "HV1R"])].copy()
    df = df.reset_index(drop=True)

    df["HV1 Trace Range Adjusted"] = ""
    df["HV1 Trace Variants Adjusted"] = ""
    for idx, row in df.iterrows():
        adj_range, adj_vars = trim_trace_hv1(row.get("MS Range", ""), row.get("Variant Converted 2", ""))
        df.at[idx, "HV1 Trace Range Adjusted"] = adj_range
        df.at[idx, "HV1 Trace Variants Adjusted"] = adj_vars

    lid_records = []
    traces_out = df.copy()
    total_lid = 0
    pair_counter = Counter()
    review_counter = Counter()

    for lid, g in df.groupby("LID", dropna=False):
        total_lid += 1
        pair, counts = select_trace_pair(g)
        hv1f = pair["HV1F"]
        hv1r = pair["HV1R"]
        pair_rows = [r for r in [hv1f, hv1r] if r is not None]

        if hv1f is not None and hv1r is not None:
            pair_status = "OK"
        elif hv1f is not None:
            pair_status = "Missing HV1R"
        elif hv1r is not None:
            pair_status = "Missing HV1F"
        else:
            pair_status = "Missing HV1F and HV1R"

        pair_counter[pair_status] += 1

        merged_ranges = []
        for r in pair_rows:
            merged_ranges.extend(parse_multi_ranges(r.get("HV1 Trace Range Adjusted", "")))
        merged_ranges = normalize_ranges(merged_ranges, merge_adjacent=False)
        merged_range_text = format_ranges(merged_ranges)

        merged_variants = merge_unique_tokens(
            [r.get("HV1 Trace Variants Adjusted", "") for r in pair_rows],
            merged_ranges,
        )

        mismatches = mismatch_positions_between_two_rows(hv1f, hv1r) if hv1f is not None and hv1r is not None else []
        mismatch_text = " ".join(
            sorted(set(mismatches), key=lambda x: float(x) if re.match(r"^\d+(\.\d+)?$", x) else 10**9)
        )

        flags, review_flags = build_hv1_flags(
            pair_status,
            merged_ranges,
            merged_variants,
            mismatch_text,
            hv1f_row=hv1f,
            hv1r_row=hv1r,
        )
        cls = review_class(review_flags)
        review_counter[cls] += 1

        first = g.iloc[0].to_dict()
        lid_records.append(
            {
                "Batch": first.get("Batch", ""),
                "Well": first.get("Well", ""),
                "LID": lid,
                "HV1 Pair Status": pair_status,
                "HV1F Candidate Count": counts.get("HV1F", 0),
                "HV1R Candidate Count": counts.get("HV1R", 0),
                "HV1F Selected Trace #": "" if hv1f is None else hv1f.get("Trace #", ""),
                "HV1R Selected Trace #": "" if hv1r is None else hv1r.get("Trace #", ""),
                "HV1F Selected Sample Name": "" if hv1f is None else hv1f.get("Sample Name", ""),
                "HV1R Selected Sample Name": "" if hv1r is None else hv1r.get("Sample Name", ""),
                "Range by HV1 Region Adjusted": merged_range_text,
                "Variants by HV1 Region Adjusted": merged_variants,
                "Mismatch by HV1 Region Adjusted": mismatch_text,
                "HV1 Flag list": flags,
                "HV1 Review-triggering Flag list": review_flags,
                "HV1 Review Class": cls,
            }
        )

        for i in g.index:
            traces_out.at[i, "HV1 Pair Status"] = pair_status
            traces_out.at[i, "Range by HV1 Region Adjusted"] = merged_range_text
            traces_out.at[i, "Variants by HV1 Region Adjusted"] = merged_variants
            traces_out.at[i, "Mismatch by HV1 Region Adjusted"] = mismatch_text
            traces_out.at[i, "HV1 Flag list"] = flags
            traces_out.at[i, "HV1 Review-triggering Flag list"] = review_flags
            traces_out.at[i, "HV1 Review Class"] = cls

    lid_df = pd.DataFrame(lid_records)

    summary_rows = [{"Metric": "Total LID", "Value": total_lid}]
    for k, v in pair_counter.items():
        summary_rows.append({"Metric": f"Pair Status - {k}", "Value": v})
    for k, v in review_counter.items():
        summary_rows.append({"Metric": f"Review Class - {k}", "Value": v})

    flag_counter = Counter()
    for flags in lid_df.get("HV1 Flag list", []):
        if safe_str(flags):
            for f in safe_str(flags).split("; "):
                flag_counter[f] += 1
    for k, v in flag_counter.most_common():
        summary_rows.append({"Metric": f"Flag - {k}", "Value": v})

    review_flag_counter = Counter()
    for flags in lid_df.get("HV1 Review-triggering Flag list", []):
        if safe_str(flags):
            for f in safe_str(flags).split("; "):
                review_flag_counter[f] += 1
    for k, v in review_flag_counter.most_common():
        summary_rows.append({"Metric": f"Review-triggering Flag - {k}", "Value": v})

    summary_df = pd.DataFrame(summary_rows)

    Path(args.output).parent.mkdir(parents=True, exist_ok=True)
    with pd.ExcelWriter(args.output, engine="openpyxl") as writer:
        traces_out.to_excel(writer, sheet_name="Traces", index=False)
        lid_df.to_excel(writer, sheet_name="LID", index=False)
        summary_df.to_excel(writer, sheet_name="Summary", index=False)

        for _, worksheet in writer.sheets.items():
            worksheet.freeze_panes = "A2"
            worksheet.auto_filter.ref = worksheet.dimensions
            for col in worksheet.columns:
                max_len = 0
                col_letter = col[0].column_letter
                for cell in col:
                    value = "" if cell.value is None else str(cell.value)
                    max_len = max(max_len, len(value))
                worksheet.column_dimensions[col_letter].width = min(max_len + 2, 50)

    print(f"Saved: {args.output}")
    print("Summary:")
    print(f"  Total LID: {total_lid}")
    for k, v in pair_counter.items():
        print(f"  Pair Status - {k}: {v}")
    for k, v in review_counter.items():
        print(f"  Review Class - {k}: {v}")


if __name__ == "__main__":
    main()
